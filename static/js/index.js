let authMode = "login"; // register | login

function openAuth(mode) {
  authMode = mode === "login" ? "login" : "register";
  const modal = document.getElementById("authModal");
  if (!modal) return;
  syncAuthUi();
  document.getElementById("authStatus").textContent = "";
  document.getElementById("authStatus").className = "status";
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
}

function closeAuth() {
  const modal = document.getElementById("authModal");
  if (!modal) return;
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
}

function syncAuthUi() {
  const L = getLang();
  const pack = I18N[L] || I18N.en;
  const reg = authMode === "register";
  const title = document.getElementById("authTitle");
  const sub = document.getElementById("authSub");
  const submit = document.getElementById("authSubmit");
  const sw = document.getElementById("authSwitch");
  const em = document.getElementById("authEmail");
  const pw = document.getElementById("authPass");
  if (title) title.textContent = reg ? pack.auth_title_reg : pack.auth_title_login;
  if (sub) sub.textContent = reg ? pack.auth_sub_reg : pack.auth_sub_login;
  if (submit) submit.textContent = reg ? pack.auth_submit_reg : pack.auth_submit_login;
  if (sw) {
    sw.innerHTML = reg ? pack.auth_switch_reg : pack.auth_switch_login;
    const tog = document.getElementById("authToggle");
    if (tog) tog.onclick = function (e) {
      e.preventDefault();
      authMode = reg ? "login" : "register";
      syncAuthUi();
    };
  }
  if (em) em.placeholder = pack.ph_email;
  if (pw) pw.placeholder = pack.ph_pass;
}

async function submitAuth() {
  const L = getLang();
  const pack = I18N[L] || I18N.en;
  const email = (document.getElementById("authEmail").value || "").trim();
  const password = document.getElementById("authPass").value || "";
  const st = document.getElementById("authStatus");
  const url = authMode === "register" ? "/api/auth/register" : "/api/auth/login";
  st.className = "status";
  st.textContent = L === "ru" ? "…" : "…";
  try {
    const r = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      credentials: "include",
      body: JSON.stringify({ email: email, password: password })
    });
    let j = {};
    try { j = await r.json(); } catch (e) {}
    if (!j.ok) {
      st.className = "status err";
      st.textContent = j.msg || pack.auth_err;
      return;
    }
    st.className = "status ok";
    st.textContent = authMode === "register" ? pack.auth_ok_reg : pack.auth_ok_login;
    try { refreshHomeUser(true); } catch (e) {}
    // stay on home — do not force /app
    setTimeout(function () { closeAuth(); }, 1200);
  } catch (e) {
    st.className = "status err";
    st.textContent = String(e);
  }
}


async function refreshHomeUser(force) {
  const pill = document.getElementById("navUserPill");
  const reg = document.getElementById("navReg");
  const logout = document.getElementById("navLogout");
  try {
    // ss-shell.js already fetches this on every page load. Reuse its response
    // instead of asking the server about the same session a second time; pass
    // force=true where the state must actually be re-read (after a login).
    const sh = window.SSShell;
    let j;
    if (sh && sh.me) {
      j = await (force ? sh.loadMe() : sh.me());
    } else {
      const r = await fetch("/api/bootstrap", { credentials: "include" });
      j = await r.json();
    }
    if (j && j.ok && j.logged_in) {
      if (pill) {
        const label = (j.display_name || "").trim() || (j.email || "").trim() || "Account";
        pill.textContent = label;
        pill.title = j.email || label;
        pill.href = "/profile/" + encodeURIComponent(j.profile_username || j.username || (j.email || "profile").split("@")[0]);
        pill.classList.add("visible");
      }
      if (reg) { reg.style.setProperty("display", "none", "important"); reg.hidden = true; }
      if (logout) { logout.hidden = false; logout.style.setProperty("display", "inline-flex", "important"); }
      return;
    }
  } catch (e) {}
  if (pill) { pill.classList.remove("visible"); pill.textContent = ""; }
  if (reg) { reg.hidden = false; reg.style.setProperty("display", "inline-flex", "important"); }
  if (logout) { logout.hidden = true; logout.style.setProperty("display", "none", "important"); }
}
